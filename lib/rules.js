const OPPOSITE_SIDE_EXTRA_POINTS = new Set(['公孫', '足臨泣', '申脈', '照海']);

export function evaluateExtraordinaryMeridian(rightDir, leftDir, zhongshiResult) {
  if (!rightDir && !leftDir) return null;

  const matchedPoints = [];
  const addPoint = (pt) => { if (!matchedPoints.includes(pt)) matchedPoints.push(pt); };

  if (rightDir === 'right' && leftDir === 'right') addPoint('公孫');
  if (rightDir === 'up-left' || leftDir === 'down-left') addPoint('列缺');
  if (leftDir === 'up-left' || rightDir === 'down-left') addPoint('後溪');
  if (rightDir === 'left' || leftDir === 'left') addPoint('足臨泣');
  if (rightDir === 'up-right' || leftDir === 'up-right') addPoint('申脈');
  if (rightDir === 'down-right' || leftDir === 'down-right') addPoint('照海');
  if (rightDir === 'up' && leftDir === 'up') addPoint('外關');
  if (rightDir === 'down' && leftDir === 'down') addPoint('內關');

  if (matchedPoints.length === 0) {
    return {
      status: 'unmatched',
      message: '脈象不完全符合奇經八脈',
      points: []
    };
  }

  let yinAction = null;
  let yinType = 'tonify';
  if (zhongshiResult) {
    const isMaikou = zhongshiResult.method && zhongshiResult.method.includes('脈口');
    yinAction = isMaikou ? zhongshiResult.sedate : zhongshiResult.tonify;
    yinType = isMaikou ? 'sedate' : 'tonify';
  }

  const points = matchedPoints.map((pt) => {
    if (!yinAction) {
      return { point: pt, side: null, desc: '遠心、順轉（請先選擇上方寸關尺脈位以決定左右側）', type: yinType };
    }
    const isOpposite = OPPOSITE_SIDE_EXTRA_POINTS.has(pt);
    const side = isOpposite ? (yinAction.side === 'left' ? 'right' : 'left') : yinAction.side;
    return {
      point: pt,
      side,
      desc: yinAction.desc,
      type: yinType
    };
  });

  return {
    status: matchedPoints.length >= 2 ? 'multiple' : 'single',
    note: matchedPoints.length >= 2 ? '脈象同時符合兩條奇經八脈，請斟酌參考' : null,
    points
  };
}

